/** Курс, пов'язаний з вебінаром (або null). */
function academyCourseFor(webinar) {
  if (!webinar) return null;
  const code = webinar.courseCode || ACADEMY.webinarCourse[webinar.id];
  const c = ACADEMY.courses.find(x => x.code === code);
  return c && c.status === 'open' && c.url ? c : null;
}
